        news_bulk = []
        
        for i in range(count):
            if i < 30:
                category = 'it'
                title = IT_TITLES[i % len(IT_TITLES)]
                content = random.choice(IT_CONTENT_TEMPLATES).format(company=fake.company())
            elif i < 60:
                category = 'science'
                title = SCIENCE_TITLES[i % len(SCIENCE_TITLES)]
                content = random.choice(SCIENCE_CONTENT_TEMPLATES)
            else:
                category = 'tech'
                title = TECH_TITLES[i % len(TECH_TITLES)]
                content = random.choice(TECH_CONTENT_TEMPLATES)

            slug = slugify(title) or f'news-{i}'
            base_slug = slug
            counter = 1
            while News.objects.filter(slug=slug).exists() or any(n.slug == slug for n in news_bulk):
                slug = f"{base_slug}-{counter}"
                counter += 1

            excerpt = content[:297] + '...' if len(content) > 300 else content

            news = News(
                title=title,
                slug=slug,
                content=content,
                excerpt=excerpt,
                category=category,
                author=user,
                views=random.randint(100, 5000),
                status='published',
                created_at=now - timedelta(
                    days=random.randint(0, 60),
                    hours=random.randint(0, 23),
                    minutes=random.randint(0, 59),
                ),
            )
            news_bulk.append(news)

        News.objects.bulk_create(news_bulk)
        self.stdout.write(self.style.SUCCESS(f'Создано {len(news_bulk)} новостей'))
