class Command(BaseCommand):
    help = 'Создаёт 10 вымышленных новостей для каждой категории (всего 30)'

    def handle(self, *args, **options):
        News.objects.all().delete()

        user, _ = User.objects.get_or_create(
            username='admin',
            defaults={'is_staff': True, 'is_superuser': True}
        )
        if not user.password or user.password.startswith('!'):
            user.set_password('admin')
            user.save()

        now = timezone.now()
        news_bulk = []

        categories = [
            ('it', FAKE_IT_TITLES, FAKE_IT_CONTENT),
            ('science', FAKE_SCIENCE_TITLES, FAKE_SCIENCE_CONTENT),
            ('tech', FAKE_TECH_TITLES, FAKE_TECH_CONTENT),
        ]

        for category, titles, contents in categories:
            for i in range(10):
                title = titles[i]
                content = contents[i]

                slug = slugify(title)
                base_slug = slug
                counter = 1
                while News.objects.filter(slug=slug).exists() or any(n.slug == slug for n in news_bulk):
                    slug = f"{base_slug}-{counter}"
                    counter += 1

                excerpt = content[:297] + '...' if len(content) > 300 else content

                news = News(
                    title=title,
                    slug=slug,
                    content=content.strip(),
                    excerpt=excerpt,
                    category=category,
                    author=user,
                    views=random.randint(100, 5000),
                    status='published',
                    created_at=now - timedelta(
                        days=random.randint(0, 60),
                        hours=random.randint(0, 23),
                        minutes=random.randint(0, 59),
                    ),
                )
                news_bulk.append(news)

        News.objects.bulk_create(news_bulk)
        self.stdout.write(self.style.SUCCESS(f'Создано {len(news_bulk)} вымышленных новостей (по 10 на категорию)'))
        self.stdout.write(f'  IT: {len([n for n in news_bulk if n.category == "it"])}')
        self.stdout.write(f'  Наука: {len([n for n in news_bulk if n.category == "science"])}')
        self.stdout.write(f'  Техника: {len([n for n in news_bulk if n.category == "tech"])}')
