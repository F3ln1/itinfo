def add_paragraph(text, bold=False, italic=False, alignment=None, first_line_indent=Cm(1.25)):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.bold = bold
    run.italic = italic
    p.paragraph_format.line_spacing = 1.5
    if first_line_indent:
        p.paragraph_format.first_line_indent = first_line_indent
    if alignment:
        p.paragraph_format.alignment = alignment
    return p


def add_bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    p.clear()
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    p.paragraph_format.line_spacing = 1.5
    return p


